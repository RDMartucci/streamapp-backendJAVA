package com.streamapp.streamappbackend.entity;

import jakarta.persistence.*;

import java.time.Instant;

@Entity
@Table(name = "user_roots", uniqueConstraints = {
        @UniqueConstraint(name = "uq_user_roots_path", columnNames = {"user_id", "root_path"})
})
public class UserRoot {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    @Column(name = "root_path", nullable = false, length = 1024)
    private String path;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @PrePersist
    void prePersist() {
        if (createdAt == null) {
            createdAt = Instant.now();
        }
    }

    public Long getId() {
        return id;
    }

    public User getUser() {
        return user;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public String getPath() {
        return path;
    }

    public void setPath(String path) {
        this.path = path;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }
}